"""View, server side: turn a model snapshot into what the page displays.

All wording the user reads about state (button labels and order, outcome
labels) is chosen here. The browser half of the view is in `static/`; it
draws this description and forwards user actions. Neither half imports the
backend, the reader or the interpreter.
"""
from .contract import Operation, Outcome
from .controller import Reply
from .examples import Example
from .model import MAX_SOURCE_BYTES, Result, Snapshot

# Button order required by the assignment.
ACTIONS = (
    (Operation.LINT, "Lint",
     "Checks that every variable is declared. Does not run the program."),
    (Operation.INTERPRET, "Interpret",
     "Runs the program and shows the value it produces, or the error."),
    (Operation.TYPECHECK, "Type-check",
     "Will check types. Not implemented yet, so it only says so."),
    (Operation.COMPILE, "Compile",
     "Will generate code. Not implemented yet, so it only says so."),
    (Operation.EXECUTE, "Execute",
     "Will run code generated by Compile. Unavailable until Compile exists."),
)
_ACTION_LABELS = {operation: label for operation, label, _ in ACTIONS}

_OUTCOME_LABELS = {
    Outcome.SUCCESS: "Success",
    Outcome.INPUT_ERROR: "Input error",
    Outcome.LANGUAGE_ERROR: "Error",
    Outcome.TIMEOUT: "Timed out",
    Outcome.BACKEND_FAILURE: "Backend failure",
    Outcome.NOT_IMPLEMENTED: "Not implemented",
}


def outcome_label(result: Result) -> str:
    if result.outcome is Outcome.LANGUAGE_ERROR:
        if result.operation is Operation.LINT:
            return "Lint error"
        if result.operation is Operation.INTERPRET:
            return "Runtime error"
    return _OUTCOME_LABELS[result.outcome]


def render_reply(reply: Reply, examples: tuple[Example, ...]) -> dict:
    return {
        "status": reply.status.value,
        "message": reply.message,
        "state": render_state(reply.snapshot, examples),
    }


def render_state(snapshot: Snapshot, examples: tuple[Example, ...]) -> dict:
    source = snapshot.source
    return {
        "source": None if source is None else {
            "name": source.name, "revision": source.revision, "text": source.text},
        "editor": {
            "name": snapshot.editor_name,
            "base": snapshot.editor_base,
            "text": snapshot.editor_text,
            "hasUnappliedEdits": snapshot.has_unapplied_edits,
        },
        "busy": None if snapshot.busy is None else {
            "operation": snapshot.busy.value, "label": _ACTION_LABELS[snapshot.busy]},
        "actions": [
            {"id": operation.value, "label": label, "description": description,
             "enabled": snapshot.blocked[operation] is None,
             "reason": snapshot.blocked[operation]}
            for operation, label, description in ACTIONS],
        "results": [
            {"operation": result.operation.value,
             "operationLabel": _ACTION_LABELS[result.operation],
             "revision": result.revision,
             "outcome": result.outcome.value,
             "outcomeLabel": outcome_label(result),
             "text": result.text}
            for result in snapshot.results],
        "hasArtifact": snapshot.artifact is not None,
        "examples": [{"key": example.key, "label": example.name} for example in examples],
        "maxSourceBytes": MAX_SOURCE_BYTES,
    }
