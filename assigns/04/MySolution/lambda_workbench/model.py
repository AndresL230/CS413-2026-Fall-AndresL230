"""Model: the workbench state and the rules for changing it.

Nothing here knows about HTTP, HTML, the browser or how a language tool is
run. The model owns the applied source and its revision, the editor draft,
the results for the current revision, any generated-code artifact, and the
busy flag. Every rule about what may happen when is enforced here, so it
holds no matter which view or controller is attached.
"""
import threading
from dataclasses import dataclass, replace

from .contract import Artifact, Operation, Outcome, ToolOutput

# Largest accepted source, measured in UTF-8 encoded bytes.
MAX_SOURCE_BYTES = 64 * 1024

MANUAL_INPUT_NAME = "Manual input"

# Results kept for the current revision, newest first.
MAX_RESULTS = 20

SOURCE_OPERATIONS = (Operation.LINT, Operation.INTERPRET, Operation.TYPECHECK, Operation.COMPILE)

EXECUTE_UNAVAILABLE = (
    "Execute runs code generated by Compile. Compilation is not yet implemented, "
    "so no generated code exists.")


class ModelError(Exception):
    """A request the current state does not allow. The state is unchanged."""


class SourceRejected(ModelError):
    """The proposed source is empty, too large or not valid UTF-8."""


class BusyError(ModelError):
    """An operation is running; nothing else may change until it finishes."""


class UnappliedEdits(ModelError):
    """The editor holds changes that were neither applied nor discarded."""


class OperationUnavailable(ModelError):
    """The operation has nothing to work on yet."""


@dataclass(frozen=True)
class AppliedSource:
    name: str
    text: str
    revision: int


@dataclass(frozen=True)
class Result:
    operation: Operation
    revision: int
    outcome: Outcome
    text: str


@dataclass(frozen=True)
class Ticket:
    """Permission to run one operation, with everything the backend needs."""
    operation: Operation
    revision: int
    source: str
    artifact: Artifact | None


@dataclass(frozen=True)
class Snapshot:
    """A consistent, read-only copy of the state for a view to present."""
    source: AppliedSource | None
    editor_name: str
    # The text the editor started from and the text it holds now.
    editor_base: str
    editor_text: str
    has_unapplied_edits: bool
    busy: Operation | None
    results: tuple[Result, ...]
    artifact: Artifact | None
    # For each operation, None if it may run now, otherwise the reason it may not.
    blocked: dict[Operation, str | None]


def decode_upload(data: bytes) -> str:
    """Decode an uploaded file, or raise SourceRejected."""
    if len(data) > MAX_SOURCE_BYTES:
        raise SourceRejected(_too_large(len(data)))
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise SourceRejected("The file is not valid UTF-8 text.") from None


def _too_large(size: int) -> str:
    return f"The source is {size} bytes; the limit is {MAX_SOURCE_BYTES} bytes."


def _normalize(text: str) -> str:
    """Use one line-ending convention, the one a browser text area reports.

    Without this, a file saved with Windows line endings would never compare
    equal to the editor that displays it.
    """
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _validate(text: str) -> None:
    if not text.strip():
        raise SourceRejected("The source is empty.")
    try:
        size = len(text.encode("utf-8"))
    except UnicodeEncodeError:
        raise SourceRejected("The source is not valid UTF-8 text.") from None
    if size > MAX_SOURCE_BYTES:
        raise SourceRejected(_too_large(size))


class Workbench:
    def __init__(self):
        self._lock = threading.RLock()
        self._source: AppliedSource | None = None
        self._revision = 0
        # The editor: the name its content would be applied under, the text it
        # started from, and the text it holds now.
        self._editor_name = MANUAL_INPUT_NAME
        self._editor_base = ""
        self._draft = ""
        self._busy: Operation | None = None
        self._results: list[Result] = []
        self._artifact: Artifact | None = None

    # --- queries -------------------------------------------------------

    def snapshot(self) -> Snapshot:
        with self._lock:
            return Snapshot(
                source=self._source,
                editor_name=self._editor_name,
                editor_base=self._editor_base,
                editor_text=self._draft,
                has_unapplied_edits=self._has_unapplied_edits(),
                busy=self._busy,
                results=tuple(self._results),
                artifact=self._artifact,
                blocked={operation: self._why_blocked(operation) for operation in Operation})

    def _has_unapplied_edits(self) -> bool:
        return self._draft != self._editor_base

    def _why_blocked(self, operation: Operation) -> str | None:
        if self._busy is not None:
            return f"{self._busy.value} is running."
        if self._has_unapplied_edits():
            return "Apply or discard the changes in the editor first."
        if self._source is None or self._editor_base != self._source.text:
            return "Apply a source first."
        if operation is Operation.EXECUTE and self._artifact is None:
            return EXECUTE_UNAVAILABLE
        return None

    # --- source changes ------------------------------------------------

    def load(self, name: str, text: str) -> AppliedSource:
        """Replace the source with an uploaded file or a canned example."""
        with self._lock:
            self._require_idle()
            self._require_no_unapplied_edits()
            text = _normalize(text)
            _validate(text)
            return self._accept(name, text)

    def open_manual_input(self) -> None:
        """Show a blank editor. The applied source stays until Apply."""
        with self._lock:
            self._require_idle()
            self._require_no_unapplied_edits()
            self._editor_name = MANUAL_INPUT_NAME
            self._editor_base = self._draft = ""

    def edit(self, text: str) -> None:
        """Record what the editor currently holds."""
        with self._lock:
            self._require_idle()
            self._draft = _normalize(text)

    def apply_edits(self) -> AppliedSource:
        """Make the editor text the applied source, as a new revision."""
        with self._lock:
            self._require_idle()
            _validate(self._draft)
            if not self._has_unapplied_edits():
                raise ModelError("There are no changes to apply.")
            return self._accept(self._editor_name, self._draft)

    def discard_edits(self) -> None:
        """Return the editor to the applied source, or to blank if there is none."""
        with self._lock:
            self._require_idle()
            if self._source is not None:
                self._editor_name = self._source.name
                self._editor_base = self._draft = self._source.text
            else:
                self._editor_base = self._draft = ""

    def _accept(self, name: str, text: str) -> AppliedSource:
        self._revision += 1
        self._source = AppliedSource(name, text, self._revision)
        self._editor_name = name
        self._editor_base = self._draft = text
        self._results.clear()
        self._artifact = None
        return self._source

    # --- operations ----------------------------------------------------

    def begin(self, operation: Operation) -> Ticket:
        """Mark the workbench busy and return what the operation runs on."""
        with self._lock:
            reason = self._why_blocked(operation)
            if reason is not None:
                if self._busy is not None:
                    raise BusyError(f"Busy: {reason}")
                if self._has_unapplied_edits():
                    raise UnappliedEdits(reason)
                raise OperationUnavailable(reason)
            self._busy = operation
            return Ticket(operation, self._source.revision, self._source.text, self._artifact)

    def finish(self, ticket: Ticket, output: ToolOutput) -> Result:
        """Record the result of the operation `ticket` and clear the busy flag."""
        with self._lock:
            if self._busy is not ticket.operation or ticket.revision != self._revision:
                raise ModelError("This operation is not the one in progress.")
            self._busy = None
            if ticket.operation is Operation.COMPILE:
                # A failed or placeholder compilation leaves no artifact behind.
                self._artifact = None
                if output.outcome is Outcome.SUCCESS and output.artifact is not None:
                    self._artifact = replace(output.artifact, revision=ticket.revision)
            result = Result(ticket.operation, ticket.revision, output.outcome, output.text)
            self._results.insert(0, result)
            del self._results[MAX_RESULTS:]
            return result

    def _require_idle(self) -> None:
        if self._busy is not None:
            raise BusyError(f"Busy: {self._busy.value} is running.")

    def _require_no_unapplied_edits(self) -> None:
        if self._has_unapplied_edits():
            raise UnappliedEdits("Apply or discard the changes in the editor first.")
