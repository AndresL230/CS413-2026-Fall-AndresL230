"""Backend adapter: the only module that knows how the language tools are run.

`LambdaBackend` implements the `contract.Backend` operations. Lint and
Interpret are real and run `lambda1.py` in a worker process with a time
bound. Type-check and Compile are placeholders, and Execute has nothing to
run until a compiler produces an artifact.
"""
import json
import subprocess
import sys
from pathlib import Path

from .contract import Artifact, Operation, Outcome, ToolOutput

DEFAULT_TIMEOUT_SECONDS = 5.0

# Directory that contains the lambda_workbench package.
_PACKAGE_PARENT = Path(__file__).resolve().parent.parent


class LambdaBackend:
    def __init__(self, timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS):
        self.timeout_seconds = timeout_seconds

    def lint(self, source: str) -> ToolOutput:
        return self._run_worker(Operation.LINT, source)

    def interpret(self, source: str) -> ToolOutput:
        return self._run_worker(Operation.INTERPRET, source)

    def typecheck(self, source: str) -> ToolOutput:
        return ToolOutput(Outcome.NOT_IMPLEMENTED, "Type checking is not yet implemented.")

    def compile(self, source: str) -> ToolOutput:
        return ToolOutput(
            Outcome.NOT_IMPLEMENTED,
            "Compilation is not yet implemented. No generated code was produced, "
            "so Execute stays unavailable.")

    def execute(self, artifact: Artifact | None) -> ToolOutput:
        if artifact is None:
            return ToolOutput(
                Outcome.NOT_IMPLEMENTED,
                "Execute runs code generated by Compile. No generated code exists.")
        return ToolOutput(
            Outcome.NOT_IMPLEMENTED,
            f"Executing generated {artifact.language} code is not yet implemented.")

    def _run_worker(self, operation: Operation, source: str) -> ToolOutput:
        request = json.dumps({"operation": operation.value, "source": source})
        try:
            finished = subprocess.run(
                [sys.executable, "-m", "lambda_workbench.tool_worker"],
                input=request, capture_output=True, text=True, encoding="utf-8",
                cwd=_PACKAGE_PARENT, timeout=self.timeout_seconds)
        except subprocess.TimeoutExpired:
            return ToolOutput(
                Outcome.TIMEOUT,
                f"Stopped after {self.timeout_seconds:g} seconds without a result. "
                "The program may not terminate.")
        except OSError as exc:
            return ToolOutput(Outcome.BACKEND_FAILURE, f"Could not start the language tool: {exc}")
        try:
            reply = json.loads(finished.stdout)
            return ToolOutput(Outcome(reply["outcome"]), str(reply["text"]))
        except (ValueError, KeyError, TypeError):
            detail = finished.stderr.strip().splitlines()[-1:] or ["no output"]
            return ToolOutput(
                Outcome.BACKEND_FAILURE,
                f"The language tool failed (exit status {finished.returncode}): {detail[0]}")
